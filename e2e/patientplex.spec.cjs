const {test, expect} = require('@playwright/test');
const base = 'http://localhost:3000';
const api = 'http://localhost:8000/api/v1';
test('doctor signup, onboarding, login, CRM and booking', async ({page}, info) => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if(r.url().startsWith(api) && r.status() >= 500) errors.push(r.status()+' '+new URL(r.url()).pathname); });
  await page.route('**/*', route => {
    const u = new URL(route.request().url());
    return ['localhost','127.0.0.1'].includes(u.hostname) ? route.continue() : route.abort();
  });
  const email = 'e2e-'+Date.now()+'@example.com';
  const password = 'SyntheticTest123!';
  await page.goto(base+'/signup');
  await page.getByPlaceholder('Dr. Priya Sharma').fill('Synthetic Doctor');
  await page.getByPlaceholder('priya@clinic.com').fill(email);
  await page.getByPlaceholder('9876543210').fill('9000000001');
  await page.getByPlaceholder('At least 8 characters').fill(password);
  await page.getByPlaceholder('Repeat your password').fill(password);
  const signup = page.waitForResponse(r=>r.url()===api+'/auth/signup' && r.request().method()==='POST');
  await page.getByRole('button',{name:'Create account'}).click();
  expect((await signup).status()).toBe(201);
  await expect(page).toHaveURL(/onboarding/);
  await page.getByRole('button',{name:/dentist/i}).first().click();
  await page.getByRole('button',{name:'Continue'}).click();
  await page.getByPlaceholder('Sharma Dental Clinic').fill('Synthetic Clinic');
  await page.getByPlaceholder('123, MG Road, Near City Mall...').fill('123 Test Road');
  await page.getByPlaceholder('Hyderabad').fill('Hyderabad');
  await page.getByPlaceholder('Telangana').fill('Telangana');
  await page.getByPlaceholder('500032').fill('500032');
  await page.getByRole('button',{name:'Continue'}).click();
  await expect(page.getByRole('heading',{name:'Set your monthly budget'})).toBeVisible();
  await page.getByRole('button',{name:'Continue'}).click();
  await page.getByPlaceholder('9876543210').fill('9000000001');
  const complete = page.waitForResponse(r=>r.url()===api+'/onboarding/complete');
  await page.getByRole('button',{name:'Complete Setup'}).click();
  expect((await complete).ok()).toBeTruthy();
  await expect(page).toHaveURL(/dashboard/);
  await page.screenshot({path:info.outputPath('dashboard.png'),fullPage:true});
  await page.context().clearCookies();
  await page.evaluate(()=>localStorage.clear());
  await page.goto(base+'/login');
  await page.getByPlaceholder('priya@clinic.com').fill(email);
  await page.getByPlaceholder('Enter your password').fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.getByRole('link',{name:'Patients',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Patient CRM'})).toBeVisible();
  await page.getByPlaceholder('Search by name or phone...').fill('Synthetic');
  await page.screenshot({path:info.outputPath('crm.png'),fullPage:true});
  await page.getByRole('link',{name:'Appointments',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Appointments',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Log Appointment'}).click();
  await page.getByPlaceholder('e.g. Rahul Sharma').fill('Synthetic Patient');
  await page.getByPlaceholder('e.g. 9876543210').fill('9000000002');
  await page.locator('input[type=date]').fill(new Date(Date.now()+86400000).toISOString().slice(0,10));
  await page.locator('input[type=time]').fill('10:30');
  const booked = page.waitForResponse(r=>r.url()===api+'/appointments/book' && r.request().method()==='POST');
  await page.getByRole('button',{name:'Book Appointment'}).click();
  const response = await booked;
  expect(response.ok()).toBeTruthy();
  expect((await response.json()).success).not.toBe(false);
  await page.screenshot({path:info.outputPath('appointments.png'),fullPage:true});
  expect(errors).toEqual([]);
});
for(const width of [390,768,1440]) {
  test('login responsive '+width, async ({page},info)=>{
    await page.setViewportSize({width,height:900});
    await page.goto(base+'/login');
    await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
    await page.screenshot({path:info.outputPath('login-'+width+'.png'),fullPage:true});
  });
}
test('invalid login shows error',async ({page})=>{
  await page.goto(base+'/login');
  await page.getByPlaceholder('priya@clinic.com').fill('missing@example.com');
  await page.getByPlaceholder('Enter your password').fill('InvalidPassword123!');
  const result=page.waitForResponse(r=>r.url()===api+'/auth/login');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  expect((await result).status()).toBe(401);
  await expect(page).toHaveURL(/login/);
  await expect(page.locator('.bg-red-50')).toBeVisible();
});
